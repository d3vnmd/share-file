// Bundles public/ into src/assets.generated.js so both Node.js and Cloudflare
// Workers serve the UI without filesystem access.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = (f) => readFileSync(join(root, 'public', f), 'utf8');
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

const js = pub('app.js');
const css = pub('app.css');
const icon = pub('favicon.svg');
const version = hash(js + css + icon);
const html = pub('index.html').replaceAll('{{v}}', version);

const asset = (body, type, extra = {}) => ({ body, type, etag: `"${hash(body)}"`, hash: version, ...extra });
const assets = {
  '/': asset(html, 'text/html; charset=utf-8', { html: true }),
  '/assets/app.js': asset(js, 'text/javascript; charset=utf-8', { immutable: true }),
  '/assets/app.css': asset(css, 'text/css; charset=utf-8', { immutable: true }),
  '/favicon.svg': asset(icon, 'image/svg+xml', { immutable: true }),
  '/robots.txt': asset('User-agent: *\nAllow: /$\nDisallow: /\n', 'text/plain; charset=utf-8'),
};

writeFileSync(
  join(root, 'src', 'assets.generated.js'),
  `// AUTO-GENERATED by scripts/build-assets.js — do not edit.\nexport const assets = ${JSON.stringify(assets, null, 1)};\n`,
);
console.log(`assets built (version ${version})`);
